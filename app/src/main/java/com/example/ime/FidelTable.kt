  fun suggestWords(
    prefix: String,
    customWords: List<String> = emptyList(),
    limit: Int = 10,
  ): List<String> =
    AmharicDictionary.suggest(
        prefix = prefix,
        customWords = customWords,
        wordLimit = limit,
      )
      .wordCompletions
