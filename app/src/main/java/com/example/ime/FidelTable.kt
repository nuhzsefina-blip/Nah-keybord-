data class FidelFamily(
  val id: String,
  val latinKey: String,
  val phoneticHint: String,
  val orders: List<String>, // 7 standard orders: ä(e), u, i, a, ē(ie), ə(6th), o
  val labialized: List<String> = emptyList(), // e.g., ቈ ቊ ቋ ቌ ቍ or ሏ
) {
  val baseChar: String
    get() = orders[0]

  val sixthOrder: String
    get() = orders[5]

  val allVariants: List<String>
    get() = orders + labialized
}

